// Second synthetic face fixture for the "below threshold" sub-case of
// criterion 5 (two different people never match). Not generated by this
// script: a solid-color image has zero faces (covered by noFaceImage
// below), not a different detectable face at low similarity. If this file
// is missing, that sub-case is skipped with a clear reason in the evidence
// rather than faked or silently dropped. Create it the same way as
// e2e/fixtures/synthetic-adult-face.jpg (a fictional adult, no real person)
// before relying on this scenario.
const secondFaceFixturePath = 'e2e/fixtures/synthetic-adult-face-2.jpg';

// A minimal, genuinely decodable PNG with zero faces, built at runtime so
// this scenario needs no binary fixture: PNG signature + IHDR + one
// zlib-deflated IDAT (solid mid-gray, filter byte 0 per row) + IEND, each
// chunk CRC32-checked per the PNG spec. Not a photograph; Rekognition must
// still accept it as a valid image to distinguish "0 faces detected" from
// "rejected as an invalid image" (noted in Scenario D below).
function makeSolidPng(width, height, [r, g, b]) {
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c;
  });
  const crc32 = (buf) => {
    let crc = 0xffffffff;
    for (const byte of buf) crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8);
    return (crc ^ 0xffffffff) >>> 0;
  };
  const chunk = (type, data) => {
    const typeBuf = Buffer.from(type, 'ascii');
    const lengthBuf = Buffer.alloc(4);
    lengthBuf.writeUInt32BE(data.length);
    const crcBuf = Buffer.alloc(4);
    crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])));
    return Buffer.concat([lengthBuf, typeBuf, data, crcBuf]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // color type: RGB
  const rawRow = Buffer.concat([
    Buffer.from([0]),
    Buffer.from(Array.from({ length: width }, () => [r, g, b]).flat()),
  ]);
  const raw = Buffer.concat(Array.from({ length: height }, () => rawRow));
  const signature = Buffer.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
  ]);
  return Buffer.concat([
    signature,
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
const noFaceImage = makeSolidPng(200, 200, [128, 128, 128]);

async function admin(token, path, init = {}, expected = 200) {
  const response = await fetch(`${apiEndpoint}${path}`, {
    ...init,
    headers: {
      authorization: `Bearer ${token}`,
      'content-type': 'application/json',
      ...init.headers,
    },
  });
  if (response.status !== expected)
    throw new Error(
      `Admin ${path} returned ${response.status}, expected ${expected}.`,
    );
  return response.status === 204 ? undefined : response.json();
}

async function createEvent(token, name) {
  const created = await admin(
    token,
    '/admin/events',
    {
      method: 'POST',
      body: JSON.stringify({
        name,
        date: '2030-01-01T12:00:00.000Z',
        retentionDays: 1,
      }),
    },
    201,
  );
  return created.eventId;
}

// adminEvents.createPhotoUploads (src/lambdas/adminEvents.ts) ignores the
// client's requested contentType/fileName: it always signs the presigned
// URL for 'image/jpeg' and always stores at
// events/{eventId}/photos/{photoId}.photo.jpg (eventPhotoObjectKey). A PUT
// with any other content-type header fails S3's signature check, since
// content-type is a signed header (src/lambdas/lib/presignedUpload.ts). The
// no-face PNG below is still uploaded as 'image/jpeg': Rekognition decodes
// by the actual image bytes, not the declared content-type.
async function uploadPhoto(token, eventId, imageBuffer = face) {
  const upload = await admin(
    token,
    `/admin/events/${encodeURIComponent(eventId)}/photos/uploads`,
    {
      method: 'POST',
      body: JSON.stringify({
        files: [{ fileName: `${randomUUID()}.jpg`, contentType: 'image/jpeg' }],
      }),
    },
  );
  const photo = upload.uploads?.[0];
  if (!photo?.photoId || !photo?.uploadUrl)
    throw new Error('Admin upload contract was incomplete.');
  const response = await fetch(photo.uploadUrl, {
    method: 'PUT',
    headers: { 'content-type': 'image/jpeg' },
    body: imageBuffer,
  });
  if (!response.ok)
    throw new Error(`Photo presigned upload returned ${response.status}.`);
  return photo.photoId;
}

async function registerSelfie(eventId, selfieBuffer = face) {
  const response = await fetch(
    `${apiEndpoint}/events/${encodeURIComponent(eventId)}/registrations`,
    {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        email: 'synthetic@example.com',
        consentBiometrics: true,
        consentTerms: true,
      }),
    },
  );
  if (response.status !== 201)
    throw new Error(`Public registration returned ${response.status}.`);
  const body = await response.json();
  const uploaded = await fetch(body.uploadUrl, {
    method: 'PUT',
    headers: { 'content-type': 'image/jpeg', 'if-none-match': '*' },
    body: selfieBuffer,
  });
  if (uploaded.status !== 200)
    throw new Error(`Selfie presigned upload returned ${uploaded.status}.`);
  return {
    registrationId: body.registrationId,
    galleryToken: body.galleryToken,
  };
}

async function pollRegistrationStatus(registrationId, galleryToken) {
  const deadline = Date.now() + 90000;
  while (Date.now() < deadline) {
    const response = await fetch(
      `${apiEndpoint}/registrations/${encodeURIComponent(registrationId)}/status`,
      { headers: { 'X-Gallery-Token': galleryToken } },
    );
    if (response.status !== 200)
      throw new Error(`Status polling returned ${response.status}.`);
    const body = await response.json();
    if (body.status === 'ENROLLED' || body.status === 'FAILED') return body;
    await delay(1500);
  }
  throw new Error('Registration did not reach a terminal status in time.');
}

async function pollMatch(registrationId, photoId, timeoutMs = 90000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const result = await dynamo.send(
      new GetCommand({
        TableName: tableName,
        Key: { PK: `REG#${registrationId}`, SK: `MATCH#${photoId}` },
        ConsistentRead: true,
      }),
    );
    if (result.Item) return result.Item;
    await delay(2000);
  }
  return null;
}

async function countMatches(registrationId) {
  const result = await dynamo.send(
    new QueryCommand({
      TableName: tableName,
      KeyConditionExpression: 'PK = :pk AND begins_with(SK, :prefix)',
      ExpressionAttributeValues: {
        ':pk': `REG#${registrationId}`,
        ':prefix': 'MATCH#',
      },
      ConsistentRead: true,
    }),
  );
  return result.Items ?? [];
}

async function recentLogs(functionName, sinceMs, filterPattern) {
  const result = await logs.send(
    new FilterLogEventsCommand({
      logGroupName: `/aws/lambda/${functionName}`,
      startTime: sinceMs,
      filterPattern,
    }),
  );
  return (result.events ?? []).map((event) => event.message?.trim());
}

const evidence = { generatedAt: new Date().toISOString(), scenarios: {} };

async function main() {
  const userName = `acceptance87-${randomUUID()}`;
  // Leading 'A' guarantees the value never starts with '-', which the AWS
  // CLI's argument parser would otherwise mistake for a flag.
  const password = `A${randomBytes(24).toString('base64url')}a1!`;
  const registrationsToDelete = [];

  await withCleanup(async (cleanup) => {
    cleanup.add('temporary organizer', () =>
      deleteSandboxOrganizer(() =>
        run(
          'aws',
          [
            'cognito-idp',
            'admin-delete-user',
            '--user-pool-id',
            userPoolId,
            '--username',
            userName,
          ],
          '.',
        ),
      ),
    );
    run(
      'aws',
      [
        'cognito-idp',
        'admin-create-user',
        '--user-pool-id',
        userPoolId,
        '--username',
        userName,
        '--message-action',
        'SUPPRESS',
      ],
      '.',
    );
    run(
      'aws',
      [
        'cognito-idp',
        'admin-set-user-password',
        '--user-pool-id',
        userPoolId,
        '--username',
        userName,
        '--password',
        password,
        '--permanent',
      ],
      '.',
    );
    const token = run(
      'aws',
      [
        'cognito-idp',
        'initiate-auth',
        '--client-id',
        clientId,
        '--auth-flow',
        'USER_PASSWORD_AUTH',
        '--auth-parameters',
        `USERNAME=${userName},PASSWORD=${password}`,
        '--query',
        'AuthenticationResult.IdToken',
        '--output',
        'text',
      ],
      '.',
    );
    if (!token || token === 'None')
      throw new Error('Cognito did not issue an ID token.');

    const deleteFixture = (eventId, photoId) => {
      cleanup.add('photo metadata', () =>
        dynamo.send(
          new DeleteCommand({
            TableName: tableName,
            Key: { PK: `EVENT#${eventId}`, SK: `PHOTO#${photoId}` },
          }),
        ),
      );
      cleanup.add('photo object', () =>
        s3.send(
          new DeleteObjectCommand({
            Bucket: outputs.uploads_bucket_name.value,
            // eventPhotoObjectKey (src/shared/lib/s3Keys.ts): the server
            // always appends '.photo.jpg', not '.jpg'.
            Key: `events/${eventId}/photos/${photoId}.photo.jpg`,
          }),
        ),
      );
      cleanup.add('event metadata', () =>
        dynamo.send(
          new DeleteCommand({
            TableName: tableName,
            Key: { PK: `EVENT#${eventId}`, SK: 'METADATA' },
          }),
        ),
      );
    };

    // --- Scenario A: selfie before photo (regression over spec 07/#8) ---
    {
      const eventId = await createEvent(
        token,
        `Order A selfie-then-photo ${randomUUID()}`,
      );
      const startedAt = Date.now();
      const { registrationId, galleryToken } = await registerSelfie(eventId);
      registrationsToDelete.push({ registrationId, galleryToken });
      const status = await pollRegistrationStatus(registrationId, galleryToken);
      if (status.status !== 'ENROLLED')
        throw new Error(`Scenario A: registration ended ${status.status}.`);
      const photoId = await uploadPhoto(token, eventId);
      deleteFixture(eventId, photoId);
      const match = await pollMatch(registrationId, photoId);
      evidence.scenarios.A_selfie_then_photo = {
        eventId,
        registrationId,
        photoId,
        enrolledAfterMs: Date.now() - startedAt,
        match,
      };
      if (!match) throw new Error('Scenario A: no match produced.');
    }

    // --- Scenario B: photo before selfie (backfill, issue #87 core case) ---
    {
      const eventId = await createEvent(
        token,
        `Order B photo-then-selfie ${randomUUID()}`,
      );
      const startedAt = Date.now();
      const photoId = await uploadPhoto(token, eventId);
      deleteFixture(eventId, photoId);
      // The photo is already fully processed by the S3-triggered path before
      // any registration exists; confirm it produced no match yet.
      await delay(5000);
      const { registrationId, galleryToken } = await registerSelfie(eventId);
      registrationsToDelete.push({ registrationId, galleryToken });
      const enrolledAt = Date.now();
      const status = await pollRegistrationStatus(registrationId, galleryToken);
      if (status.status !== 'ENROLLED')
        throw new Error(`Scenario B: registration ended ${status.status}.`);
      const match = await pollMatch(registrationId, photoId);
      const backfillLogs = await recentLogs(
        'findly-sandbox-registration-backfill',
        startedAt,
        'registration_backfill_processed',
      );
      evidence.scenarios.B_photo_then_selfie = {
        eventId,
        registrationId,
        photoId,
        enrolledAfterMs: enrolledAt - startedAt,
        match,
        backfillLogSample: backfillLogs.at(-1) ?? null,
        backfillLogsMentionRegistrationId: backfillLogs.some((line) =>
          line?.includes(registrationId),
        ),
      };
      if (!match) throw new Error('Scenario B: backfill produced no match.');
    }

    // --- Scenario C: concurrent uploads converge without duplicating ---
    {
      const eventId = await createEvent(
        token,
        `Order C concurrent ${randomUUID()}`,
      );
      const startedAt = Date.now();
      const [{ registrationId, galleryToken }, photoId] = await Promise.all([
        registerSelfie(eventId),
        uploadPhoto(token, eventId),
      ]);
      registrationsToDelete.push({ registrationId, galleryToken });
      deleteFixture(eventId, photoId);
      const status = await pollRegistrationStatus(registrationId, galleryToken);
      if (status.status !== 'ENROLLED')
        throw new Error(`Scenario C: registration ended ${status.status}.`);
      const match = await pollMatch(registrationId, photoId);
      if (!match) throw new Error('Scenario C: no match produced.');
      // Give a slower trigger (the loser of the race) time to also attempt a
      // write before asserting there is still exactly one match.
      await delay(10000);
      const allMatches = await countMatches(registrationId);
      evidence.scenarios.C_concurrent = {
        eventId,
        registrationId,
        photoId,
        startedAt: new Date(startedAt).toISOString(),
        matchCount: allMatches.length,
        match,
      };
      if (allMatches.length !== 1)
        throw new Error(
          `Scenario C: expected exactly 1 match, found ${allMatches.length}.`,
        );
    }

    // --- Scenario D: no face / below threshold / other event never match ---
    // One registration, three photos that must each produce zero matches.
    {
      const eventId = await createEvent(
        token,
        `Order D no-match ${randomUUID()}`,
      );
      const { registrationId, galleryToken } = await registerSelfie(eventId);
      registrationsToDelete.push({ registrationId, galleryToken });
      const status = await pollRegistrationStatus(registrationId, galleryToken);
      if (status.status !== 'ENROLLED')
        throw new Error(`Scenario D: registration ended ${status.status}.`);

      // D1: no face.
      const noFacePhotoId = await uploadPhoto(token, eventId, noFaceImage);
      deleteFixture(eventId, noFacePhotoId);
      const noFaceMatch = await pollMatch(registrationId, noFacePhotoId, 30000);

      // D2/D3 need a genuinely different face: D2 to prove two distinct
      // people stay below threshold, D3 to populate the other event's
      // Rekognition collection with someone who isn't this registrant (an
      // event with no ENROLLED selfie at all has no collection yet — see
      // the lazy-creation finding in docs/evidence/issue-87-matching-
      // convergence.md — which would make D3 pass for the wrong reason:
      // ResourceNotFoundException, not real cross-collection isolation).
      const hasSecondFace = existsSync(secondFaceFixturePath);
      const secondFace = hasSecondFace
        ? readFileSync(secondFaceFixturePath)
        : null;

      // D2: below threshold (a different face). Skipped with a clear reason
      // if the second fixture is absent.
      let belowThresholdResult;
      if (hasSecondFace) {
        const otherFacePhotoId = await uploadPhoto(token, eventId, secondFace);
        deleteFixture(eventId, otherFacePhotoId);
        const otherFaceMatch = await pollMatch(
          registrationId,
          otherFacePhotoId,
          30000,
        );
        belowThresholdResult = {
          photoId: otherFacePhotoId,
          match: otherFaceMatch,
        };
      } else {
        belowThresholdResult = {
          skipped: true,
          reason: `Missing fixture ${secondFaceFixturePath}; a solid-color image has zero faces, not a different face at low similarity, so it cannot substitute here.`,
        };
      }

      // D3: same face, a different event whose own Rekognition collection
      // genuinely exists (a different person enrolled there first), so a
      // null match proves collection isolation rather than an absent
      // collection trivially rejecting the IndexFaces call.
      const otherEventId = await createEvent(
        token,
        `Order D other-event ${randomUUID()}`,
      );
      let otherEventSeedRegistration = null;
      if (hasSecondFace) {
        otherEventSeedRegistration = await registerSelfie(
          otherEventId,
          secondFace,
        );
        const seedStatus = await pollRegistrationStatus(
          otherEventSeedRegistration.registrationId,
          otherEventSeedRegistration.galleryToken,
        );
        if (seedStatus.status !== 'ENROLLED')
          throw new Error(
            `Scenario D3: seed registration ended ${seedStatus.status}.`,
          );
        registrationsToDelete.push(otherEventSeedRegistration);
      }
      const crossEventPhotoId = await uploadPhoto(token, otherEventId);
      deleteFixture(otherEventId, crossEventPhotoId);
      const crossEventMatch = await pollMatch(
        registrationId,
        crossEventPhotoId,
        30000,
      );

      evidence.scenarios.D_no_incorrect_matches = {
        eventId,
        registrationId,
        noFace: { photoId: noFacePhotoId, match: noFaceMatch },
        belowThreshold: belowThresholdResult,
        otherEvent: {
          otherEventId,
          photoId: crossEventPhotoId,
          match: crossEventMatch,
          collectionSeededWithDifferentPerson: hasSecondFace,
          seedRegistrationId:
            otherEventSeedRegistration?.registrationId ?? null,
        },
      };
      if (noFaceMatch)
        throw new Error('Scenario D: a faceless photo produced a match.');
      if (belowThresholdResult.match)
        throw new Error(
          'Scenario D: a different face below threshold produced a match.',
        );
      if (crossEventMatch)
        throw new Error(
          'Scenario D: a photo in another event matched across collections.',
        );
    }

    // --- Scenario E: pagination across more photos than one backfill page ---
    // registrationBackfill.ts pages PHOTO_PAGE_SIZE=25 photos per invocation;
    // 26 photos forces a real re-enqueued continuation, not just one page.
    {
      const PHOTO_COUNT = 26;
      const eventId = await createEvent(
        token,
        `Order E pagination ${randomUUID()}`,
      );
      const startedAt = Date.now();
      const photoIds = [];
      for (let i = 0; i < PHOTO_COUNT; i++) {
        const photoId = await uploadPhoto(token, eventId);
        deleteFixture(eventId, photoId);
        photoIds.push(photoId);
      }
      const { registrationId, galleryToken } = await registerSelfie(eventId);
      registrationsToDelete.push({ registrationId, galleryToken });
      const status = await pollRegistrationStatus(registrationId, galleryToken);
      if (status.status !== 'ENROLLED')
        throw new Error(`Scenario E: registration ended ${status.status}.`);

      // Pagination needs more time than a single match: up to PHOTO_COUNT
      // Rekognition round-trips across at least two Lambda invocations.
      const deadline = Date.now() + 180000;
      let allMatches = [];
      while (Date.now() < deadline) {
        allMatches = await countMatches(registrationId);
        if (allMatches.length === PHOTO_COUNT) break;
        await delay(3000);
      }
      // CloudWatch Logs ingestion lags the DynamoDB write that unblocks the
      // match-count loop above by a few seconds; retry instead of trusting
      // a single read taken right as the last match lands.
      const logsDeadline = Date.now() + 20000;
      let backfillLogs = [];
      while (Date.now() < logsDeadline) {
        backfillLogs = await recentLogs(
          'findly-sandbox-registration-backfill',
          startedAt,
          'registration_backfill_processed',
        );
        if (backfillLogs.length >= 2) break;
        await delay(2000);
      }
      evidence.scenarios.E_pagination = {
        eventId,
        registrationId,
        photoCount: PHOTO_COUNT,
        matchCount: allMatches.length,
        // More than one invocation for the same eventId is the signal that
        // the cursor continuation actually re-enqueued, not just a single
        // Query page that happened to return everything.
        backfillInvocations: backfillLogs.length,
        backfillLogs,
      };
      if (allMatches.length !== PHOTO_COUNT)
        throw new Error(
          `Scenario E: expected ${PHOTO_COUNT} matches, found ${allMatches.length}.`,
        );
      if (backfillLogs.length < 2)
        throw new Error(
          'Scenario E: backfill did not show more than one page/invocation.',
        );
    }

    // --- Scenario F: revocation/expiry/concurrent deletion never resurrects ---
    {
      // F1: DELETE fired concurrently with the upload that would match it.
      const eventId = await createEvent(
        token,
        `Order F concurrent-erasure ${randomUUID()}`,
      );
      const { registrationId, galleryToken } = await registerSelfie(eventId);
      const status = await pollRegistrationStatus(registrationId, galleryToken);
      if (status.status !== 'ENROLLED')
        throw new Error(`Scenario F1: registration ended ${status.status}.`);
      const [photoId] = await Promise.all([
        uploadPhoto(token, eventId),
        fetch(
          `${apiEndpoint}/registrations/${encodeURIComponent(registrationId)}`,
          {
            method: 'DELETE',
            headers: { 'X-Gallery-Token': galleryToken },
          },
        ).then((response) => {
          if (response.status !== 204)
            throw new Error(
              `Scenario F1: erasure returned ${response.status}.`,
            );
        }),
      ]);
      deleteFixture(eventId, photoId);
      // Give a slower matchPhoto/backfill invocation time to lose its race
      // against the erasure marker before asserting nothing resurrected.
      await delay(15000);
      const matchesAfterErasure = await countMatches(registrationId);

      // F2: ttl manually expired (simulates "caducidad") before any photo
      // exists; a direct DynamoDB write because the public API has no way
      // to request a short-lived registration for this test.
      const eventId2 = await createEvent(
        token,
        `Order F expired-ttl ${randomUUID()}`,
      );
      const registration2 = await registerSelfie(eventId2);
      registrationsToDelete.push(registration2);
      const status2 = await pollRegistrationStatus(
        registration2.registrationId,
        registration2.galleryToken,
      );
      if (status2.status !== 'ENROLLED')
        throw new Error(`Scenario F2: registration ended ${status2.status}.`);
      await dynamo.send(
        new UpdateCommand({
          TableName: tableName,
          Key: {
            PK: `EVENT#${eventId2}`,
            SK: `REG#${registration2.registrationId}`,
          },
          UpdateExpression: 'SET #ttl = :past',
          ExpressionAttributeNames: { '#ttl': 'ttl' },
          ExpressionAttributeValues: {
            ':past': Math.floor(Date.now() / 1000) - 3600,
          },
        }),
      );
      const photoId2 = await uploadPhoto(token, eventId2);
      deleteFixture(eventId2, photoId2);
      const expiredMatch = await pollMatch(
        registration2.registrationId,
        photoId2,
        30000,
      );

      evidence.scenarios.F_revocation_expiry_concurrency = {
        concurrentErasure: {
          eventId,
          registrationId,
          photoId,
          matchCountAfterErasure: matchesAfterErasure.length,
        },
        expiredTtl: {
          eventId: eventId2,
          registrationId: registration2.registrationId,
          photoId: photoId2,
          match: expiredMatch,
        },
      };
      if (matchesAfterErasure.length !== 0)
        throw new Error(
          'Scenario F1: a match survived a concurrent registration erasure.',
        );
      if (expiredMatch)
        throw new Error('Scenario F2: an expired registration still matched.');
    }

    for (const { registrationId, galleryToken } of registrationsToDelete) {
      cleanup.add('registration erasure (defensive, best-effort)', async () => {
        try {
          await fetch(
            `${apiEndpoint}/registrations/${encodeURIComponent(registrationId)}`,
            { method: 'DELETE', headers: { 'X-Gallery-Token': galleryToken } },
          );
        } catch {
          // Best-effort: the main erasure call below already ran for most
          // registrations; this only covers one left over by a thrown error.
        }
      });
    }
    for (const { registrationId, galleryToken } of registrationsToDelete) {
      const response = await fetch(
        `${apiEndpoint}/registrations/${encodeURIComponent(registrationId)}`,
        { method: 'DELETE', headers: { 'X-Gallery-Token': galleryToken } },
      );
      if (response.status !== 204)
        throw new Error(
          `Registration erasure returned ${response.status}, expected 204.`,
        );
    }
  });

  writeFileSync(
    'docs/evidence/issue-87-acceptance-run.json',
    JSON.stringify(evidence, null, 2) + '\n',
  );
  console.log(
    'Issue #87 AWS ephemeral acceptance passed. Evidence written to docs/evidence/issue-87-acceptance-run.json',
  );
}

